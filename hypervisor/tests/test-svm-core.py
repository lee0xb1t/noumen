#!/usr/bin/env python3
"""Host-side tests for the pure SVM logic.

The hypervisor crate targets x86_64-unknown-none and cannot use `cargo test`,
and its `.cargo/config.toml` forces build-std on every crate inside the
repository. This script therefore copies the tiny harness crate from
`tests/svm-core-tests` into a temporary directory, rewrites the `#[path]`
includes to absolute paths, and runs `cargo test` there for the host target.

Covers:
  vmcb/        VMCB layout, control bits, clean bits, typed field access
  msrpm.rs     MSR permission map index formula and boundaries
  exit_info.rs exit codes, NPF/CR/IO/exception decoding
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


REPO_ROOT = Path(__file__).resolve().parent.parent


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description="Run the SVM host-side tests.")
    parser.add_argument(
        "--keep-temp",
        action="store_true",
        help="keep the generated crate for inspection instead of deleting it",
    )
    parser.add_argument(
        "--output-directory",
        default="",
        help="reuse a fixed directory instead of a fresh one under %%TEMP%%",
    )
    args = parser.parse_args(argv)

    source = REPO_ROOT / "tests" / "svm-core-tests"
    if not (source / "Cargo.toml").is_file():
        print(f"Missing harness crate: {source}", file=sys.stderr)
        return 1

    if args.output_directory.strip():
        temp = Path(args.output_directory)
        if not temp.is_absolute():
            temp = REPO_ROOT / temp
        keep_temp = True
    else:
        temp = Path(tempfile.mkdtemp(prefix="noumen-svm-core-"))
        keep_temp = args.keep_temp

    try:
        (temp / "src").mkdir(parents=True, exist_ok=True)
        shutil.copy2(source / "Cargo.toml", temp / "Cargo.toml")

        repo_slash = REPO_ROOT.as_posix()
        modules = [
            ("vmcb", f"{repo_slash}/src/arch/x86_64/svm/vmcb/mod.rs"),
            ("msrpm", f"{repo_slash}/src/arch/x86_64/svm/msrpm.rs"),
            ("exit_info", f"{repo_slash}/src/arch/x86_64/svm/exit_info.rs"),
            ("injection", f"{repo_slash}/src/arch/x86_64/svm/injection.rs"),
            ("instruction", f"{repo_slash}/src/arch/x86_64/svm/instruction.rs"),
            ("hook_events", f"{repo_slash}/src/arch/x86_64/hook_events.rs"),
            ("wait", f"{repo_slash}/src/arch/x86_64/svm/npt/hook/wait.rs"),
        ]

        lines = [
            "#![allow(dead_code)]",
            "",
            "// Generated by tests/test-svm-core.py; do not edit.",
            "",
        ]
        for name, path in modules:
            lines.append(f'#[path = "{path}"]')
            lines.append(f"pub mod {name};")
            lines.append("")

        lines.extend(
            [
                "pub mod npt {",
                f'    #[path = "{repo_slash}/src/arch/x86_64/svm/npt/types.rs"]',
                "    pub mod types;",
                "",
                f'    #[path = "{repo_slash}/src/arch/x86_64/svm/npt/state.rs"]',
                "    pub mod state;",
                "}",
                "",
            ]
        )
        (temp / "src" / "lib.rs").write_text("\n".join(lines), encoding="utf-8")

        cargo = shutil.which("cargo")
        if cargo is None:
            print("cargo was not found in PATH", file=sys.stderr)
            return 1

        env = os.environ.copy()
        env["CARGO_TARGET_DIR"] = str(temp / "target")

        offline = subprocess.run(
            [cargo, "test", "--offline"],
            cwd=str(temp),
            env=env,
            check=False,
        )
        if offline.returncode != 0:
            print("offline test run failed; retrying with registry access")
            online = subprocess.run(
                [cargo, "test"],
                cwd=str(temp),
                env=env,
                check=False,
            )
            return online.returncode
        return offline.returncode
    except OSError as error:
        print(f"failed to run the SVM core tests: {error}", file=sys.stderr)
        return 1
    finally:
        if not keep_temp:
            shutil.rmtree(temp, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
